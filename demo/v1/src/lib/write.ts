// PostgREST의 update/delete는 RLS 때문에 대상 행이 하나도 잡히지 않아도 에러가 아니라
// "성공, 0건"으로 돌아온다. 그래서 저장 버튼을 눌러도 아무 일이 일어나지 않는데
// 화면은 저장된 것처럼 다음으로 넘어간다.
//
// 실제로 어르신 이름 수정에서 이 일이 있었다. 관리자 계정은 모든 어르신을 볼 수는 있지만
// (읽기 전용 정책) 남의 어르신을 고칠 수는 없다. 목록에 뜨니 수정 버튼을 누를 수 있었고,
// UPDATE는 0건으로 조용히 지나가 "이름이 안 바뀐다"로만 보였다.
//
// 그래서 쓰기에는 항상 .select()를 붙여 몇 건이 바뀌었는지 받아오고, 0건이면 여기서
// 막는다. 0건은 네트워크나 입력 문제가 아니라 권한 문제이므로 그렇게 안내한다.
export function assertWritten<T>(rows: T[] | null, what: string): T[] {
  if (rows && rows.length > 0) return rows;
  throw new Error(`${what} 권한이 없습니다. 어르신을 등록한 본인 계정으로 로그인했는지 확인해주세요.`);
}
